from langchain_core.tools import tool

@tool
def ask_user_clarification_tool(question: str) -> str:
    """
    Вызови этот инструмент, ЕСЛИ тебе не хватает критически важных данных от пользователя 
    для выполнения исследования или подбора (например, неизвестно количество персон, предпочтения и т.д.).
    
    Args:
        question: Точный, короткий вопрос, который система должна озвучить пользователю вслух.
    """
    return f"Вопрос отправлен пользователю: {question}"